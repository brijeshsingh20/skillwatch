"""Measure the low-bandwidth payloads on the demo clips and write docs/BANDWIDTH.md.

Usage (project root):  python -m scripts.bandwidth_report [--obs-interval-min 5] [--data-dir data]
Everything below is measured from real payloads produced by the edge agent code, except the clearly labelled assumptions.
"""
import argparse
import json
import statistics
import tempfile
from datetime import date, datetime, timezone
from pathlib import Path

import cv2

from vision.config import load_config
from vision.infra_detector import Layout
from vision.lowbw import QueueRow, build_item, encode_batch, new_ingest_id
from vision.pipeline import analyse_video
from vision.sampler import sample_frames

HEADER_BYTES = 650        # assumed HTTP request + response headers per upload
TLS_HANDSHAKE_BYTES = 6000  # assumed cost of a fresh TLS connection per upload (no keep-alive between uploads)
KB = 1024


def measure_centre(code: str, data: Path) -> dict:
    layout = Layout.load(data / "layouts" / f"{code}.json")
    ref = data / "reference" / f"{code}.png"
    video = data / "videos" / f"{code}.mp4"
    cfg = load_config("lowbw")
    with tempfile.TemporaryDirectory() as tmp:
        res = analyse_video(video, code, layout, ref, cfg, thumb_dir=tmp)
        thumb = (Path(tmp) / Path(res.frame_ref).name).read_bytes()
    item = build_item(res, code, date.today(), datetime.now(timezone.utc), new_ingest_id())
    rows = [QueueRow(1, item["ingest_id"], item, thumb, 0)]

    cap = cv2.VideoCapture(str(video))
    seconds = cap.get(cv2.CAP_PROP_FRAME_COUNT) / (cap.get(cv2.CAP_PROP_FPS) or 1)
    cap.release()
    first = next(sample_frames(video, 1.0, 640)).image
    ok, jpg = cv2.imencode(".jpg", first, [cv2.IMWRITE_JPEG_QUALITY, 80])
    return {
        "code": code, "thumb_kb": len(thumb) / KB,
        "item_with_thumb": len(encode_batch(rows, True)), "item_counts_only": len(encode_batch(rows, False)),
        "video_kb_per_hour": video.stat().st_size / KB / seconds * 3600,
        "jpeg_640_q80_kb": len(jpg) / KB, "analysis_s": res.processing_seconds, "frames": res.frames_used,
    }


def kb_per_hour(item_bytes: float, obs_per_hour: float, obs_per_upload: int) -> float:
    uploads = obs_per_hour / obs_per_upload
    return (obs_per_hour * item_bytes + uploads * (HEADER_BYTES + TLS_HANDSHAKE_BYTES)) / KB


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--data-dir", default="data")
    parser.add_argument("--obs-interval-min", type=float, default=5.0)
    parser.add_argument("--out", default="docs/BANDWIDTH.md")
    args = parser.parse_args()
    data = Path(args.data_dir)
    codes = sorted(p.stem for p in (data / "layouts").glob("*.json"))
    m = [measure_centre(c, data) for c in codes]

    with_thumb = statistics.mean(x["item_with_thumb"] for x in m)
    counts_only = statistics.mean(x["item_counts_only"] for x in m)
    worst = max(x["item_with_thumb"] for x in m)
    obs_h = 60 / args.obs_interval_min
    scenarios = [
        ("A. Counts + thumbnail, upload every observation", with_thumb, obs_h, 1),
        ("B. Counts + thumbnail, batch of 6 per upload", with_thumb, obs_h, 6),
        ("C. Counts only (no thumbnail), batch of 6", counts_only, obs_h, 6),
        ("D. Worst-case thumbnail (3x larger, real scenes), batch of 6", with_thumb + 2 * statistics.mean(x["thumb_kb"] for x in m) * KB * 4 / 3, obs_h, 6),
    ]
    rows = [(name, kb_per_hour(b, o, n)) for name, b, o, n in scenarios]
    video = statistics.mean(x["video_kb_per_hour"] for x in m)
    frames = statistics.mean(x["jpeg_640_q80_kb"] for x in m) * 1800  # one 640px JPEG every 2 s

    lines = [
        "# Bandwidth estimate (low-bandwidth mode)", "",
        f"Generated by `python -m scripts.bandwidth_report`. One observation every **{args.obs_interval_min:g} minutes** "
        f"({obs_h:g} per hour) per centre. Figures are KB per hour **per centre**, during hours the centre is being monitored.", "",
        "## Result", "", "| Scenario | KB per hour per centre |", "|---|---|",
    ]
    lines += [f"| {name} | **{kb:.0f}** |" for name, kb in rows]
    lines += [
        "", f"Headline figure (scenario B, the recommended setting): **about {rows[1][1]:.0f} KB per hour per centre**, "
        f"which is roughly {rows[1][1] * 8 / 3600:.2f} kbit/s on average.", "",
        "## What is sent", "",
        f"- One JSON record per observation (counts, equipment totals, confidence, quality): about {counts_only:.0f} bytes.",
        f"- One annotated, pixelated thumbnail (224 px wide, JPEG quality 50): about {statistics.mean(x['thumb_kb'] for x in m):.1f} KB "
        f"measured on the demo clips ({worst / KB:.1f} KB largest item including base64 and JSON).",
        "- Never video. Never full-resolution frames.", "",
        "## Measured per centre (demo clips, low-bandwidth profile)", "",
        "| Centre | Thumbnail KB | Item with thumbnail (bytes) | Counts-only item (bytes) | Frames analysed | Analysis time (s, this PC) |",
        "|---|---|---|---|---|---|",
    ]
    lines += [f"| {x['code']} | {x['thumb_kb']:.1f} | {x['item_with_thumb']} | {x['item_counts_only']} | {x['frames']} | {x['analysis_s']} |" for x in m]
    lines += [
        "", "## For comparison (same clips, same machine)", "",
        f"- Uploading the video itself: about **{video:,.0f} KB per hour**. This is measured on the synthetic clips; real camera bitrates vary widely with resolution and codec settings.",
        f"- One 640 px JPEG every 2 seconds: about **{frames:,.0f} KB per hour**.", "",
        "## Assumptions (not measured)", "",
        f"- HTTP headers add about {HEADER_BYTES} bytes per upload, and each upload opens a fresh TLS connection costing about {TLS_HANDSHAKE_BYTES} bytes.",
        "- Thumbnails of the synthetic scenes compress better than real rooms. Scenario D shows a pessimistic 3x thumbnail size.",
        "- Retries after an outage send each queued item once more, so a backlog costs the same per item as normal operation; items already received are never re-sent.",
        "- The edge box does the analysis locally, so analysis time above is CPU on the centre's machine, not bandwidth.",
    ]
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("\n".join(lines))


if __name__ == "__main__":
    main()
